type clientCtxKey struct{}

func authError(w http.ResponseWriter, r *http.Request, status int, code, message string) {
	if strings.HasPrefix(r.URL.Path, "/admin/v1/") || strings.HasPrefix(r.URL.Path, "/client/v1/") {
		writeAPIError(w, status, code, message)
		return
	}
	writeErr(w, status, code, message)
}

func suppliedSecret(r *http.Request, header string) string {
	if token := bearerToken(r); token != "" {
		return token
	}
	return r.Header.Get(header)
}

func (s *Server) requireSecret(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		provided := r.Header.Get("x-auvyn-secret")
		if provided == "" || !security.ConstantTimeEqual(provided, s.cfg.AuvynSecret) {
			authError(w, r, http.StatusUnauthorized, "UNAUTHORIZED", "missing or invalid auvyn secret")
			return
		}
		next.ServeHTTP(w, r)
	})
}

func (s *Server) requireAdmin(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if s.cfg.AdminSecret == "" || s.cfg.AdminPIN == "" || s.cfg.AdminKeys == "" {
			authError(w, r, http.StatusInternalServerError, "SERVER_MISCONFIGURED",
				"ADMIN_SECRET / ADMIN_PIN / ADMIN_KEYS are not set")
			return
		}
		ok := security.ConstantTimeEqual(suppliedSecret(r, "x-admin-secret"), s.cfg.AdminSecret) &&
			security.ConstantTimeEqual(r.Header.Get("x-admin-pin"), s.cfg.AdminPIN) &&
			security.ConstantTimeEqual(r.Header.Get("x-admin-keys"), s.cfg.AdminKeys)
		if !ok {
			authError(w, r, http.StatusUnauthorized, "UNAUTHORIZED", "missing or invalid admin credentials")
			return
		}
		next.ServeHTTP(w, r)
	})
}

// requireTransactionAuth requires the per-client credentials generated by the
// admin API. The global AUVYN_SECRET is not accepted here: it is reserved for
// operational endpoints such as /api/balance and /api/ticket-mbal.
func (s *Server) requireTransactionAuth(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		secret := suppliedSecret(r, "x-client-secret")
		pin := r.Header.Get("x-client-pin")
		keys := r.Header.Get("x-client-keys")
		if secret == "" || pin == "" || keys == "" {
			authError(w, r, http.StatusUnauthorized, "UNAUTHORIZED",
				"missing x-client-secret / x-client-pin / x-client-keys")
			return
		}
		client, err := s.st.FindClientByCredentials(secret, pin, keys)
		if err != nil {
			authError(w, r, http.StatusUnauthorized, "UNAUTHORIZED", "invalid client credentials")
			return
		}
		ctx := context.WithValue(r.Context(), clientCtxKey{}, client)
		next.ServeHTTP(w, r.WithContext(ctx))
	})
}

